<?php

namespace App\Services;

use App\Models\GoogleDriveToken;
use Google\Client as GoogleClient;
use Google\Service\Drive as GoogleDriveService;
use Illuminate\Support\Facades\Log;
use RuntimeException;
use Throwable;

class GoogleDriveAuthService
{
    public const SCOPE = 'https://www.googleapis.com/auth/drive.file';

    public function isConfigured(): bool
    {
        return filled(config('services.google_drive.client_id'))
            && filled(config('services.google_drive.client_secret'))
            && filled(config('services.google_drive.redirect_uri'));
    }

    public function isConnected(): bool
    {
        return GoogleDriveToken::current() !== null;
    }

    /**
     * Build the Google consent URL. State is generated by the caller.
     */
    public function buildAuthUrl(string $state): string
    {
        return $this->baseClient($state)->createAuthUrl();
    }

    /**
     * Exchange the authorization code for tokens, fetch the account email,
     * and store the encrypted refresh token.
     */
    public function exchangeCode(string $code): GoogleDriveToken
    {
        $client = $this->baseClient();
        $tokenData = $client->fetchAccessTokenWithAuthCode($code);

        if (isset($tokenData['error'])) {
            throw new RuntimeException(
                'Google OAuth error: ' . ($tokenData['error_description'] ?? $tokenData['error'])
            );
        }

        $refreshToken = $tokenData['refresh_token'] ?? null;
        if (! is_string($refreshToken) || $refreshToken === '') {
            throw new RuntimeException(
                'Google did not return a refresh token. Revoke prior access at https://myaccount.google.com/permissions and try again.'
            );
        }

        $client->setAccessToken($tokenData);

        $email = $this->fetchAccountEmail($client);

        // Single active token — delete any previous record first.
        GoogleDriveToken::query()->delete();

        return GoogleDriveToken::create([
            'account_email' => $email,
            'refresh_token_encrypted' => $refreshToken,
            'scope' => is_string($tokenData['scope'] ?? null) ? $tokenData['scope'] : self::SCOPE,
            'authorized_at' => now(),
        ]);
    }

    /**
     * Return a Google client with a valid access token refreshed from the
     * stored refresh token.
     */
    public function getClient(): GoogleClient
    {
        $token = GoogleDriveToken::current();
        if ($token === null) {
            throw new RuntimeException('Google Drive is not connected.');
        }

        $client = $this->baseClient();

        try {
            $client->refreshToken($token->refresh_token_encrypted);
        } catch (Throwable $e) {
            throw new RuntimeException(
                'Failed to refresh Google access token: ' . $e->getMessage(),
                0,
                $e
            );
        }

        $accessToken = $client->getAccessToken();
        if (! is_array($accessToken) || isset($accessToken['error'])) {
            throw new RuntimeException('Failed to refresh Google access token.');
        }

        $token->markUsed();

        return $client;
    }

    public function getDriveService(): GoogleDriveService
    {
        return new GoogleDriveService($this->getClient());
    }

    public function disconnect(): void
    {
        $token = GoogleDriveToken::current();
        if ($token === null) {
            return;
        }

        try {
            $this->getClient()->revokeToken();
        } catch (Throwable $e) {
            Log::warning('Failed to revoke Google Drive token', ['error' => $e->getMessage()]);
        }

        $token->delete();
    }

    protected function baseClient(?string $state = null): GoogleClient
    {
        $client = new GoogleClient();
        $client->setClientId((string) config('services.google_drive.client_id'));
        $client->setClientSecret((string) config('services.google_drive.client_secret'));
        $client->setRedirectUri((string) config('services.google_drive.redirect_uri'));
        $client->addScope(self::SCOPE);
        $client->setAccessType('offline');
        $client->setPrompt('consent');
        $client->setIncludeGrantedScopes(true);

        if ($state !== null) {
            $client->setState($state);
        }

        return $client;
    }

    /**
     * Fetch the authorized account's email via the Drive about.get endpoint —
     * avoids needing the Oauth2 service (which is not installed after cleanup).
     */
    protected function fetchAccountEmail(GoogleClient $client): ?string
    {
        try {
            $drive = new GoogleDriveService($client);
            $about = $drive->about->get(['fields' => 'user']);
            return $about->getUser()?->getEmailAddress();
        } catch (Throwable $e) {
            Log::warning('Failed to fetch Google account email', ['error' => $e->getMessage()]);
            return null;
        }
    }
}